"""The admin console's audit log: who did what, to which record, and whether it was allowed.

    # db.py's schema function:  cur.execute(audit_log.schema_sql("admin_audit_log"))
    audit = AuditLog(database=db.database, table="admin_audit_log")
    audit.attach(bp)          # records every write on the admin blueprint, plus denied requests

    # in a route, when the target isn't in the URL (e.g. an email in the body):
    g.audit_target = email

What a row holds: time, actor (the admin's email, or the signed-in non-admin who was turned away), action
(the route's endpoint name, e.g. "diary_admin.delete_font"), target (the URL's ids, or g.audit_target), and
result: "ok", "denied" (401/403) or "failed" (any other 4xx/5xx). Never the request body, user-written
content, tokens or IPs.

What gets recorded, by the blueprint hook:
- every POST/PUT/PATCH/DELETE on the blueprint, whatever its outcome;
- any request turned away with 403 (a signed-in account that isn't an admin, or a login by a non-admin).
  401s without an identity aren't recorded: rejections.py already counts them, and there's nobody to name.

★ The row is written after the route has run, in its own short transaction, not in the route's. That way
  every admin route is covered without each one having to remember to log, and a route added later is
  covered too. The cost: if the database fails between the two writes, the change stands without its row.
  A failed audit write never turns a successful request into an error; it is reported as a type only.

Retention: rows older than `retention_days` are deleted by the same statement that writes a new row, so
nothing else has to run on a schedule and the table can't grow without bound.
"""

from __future__ import annotations

import logging
import re
from typing import Callable

from flask import Blueprint, g, request

from shared.database import Database

log = logging.getLogger(__name__)

_TABLE_NAME = re.compile(r"^[a-z_][a-z0-9_]{0,62}$")
_WRITE_METHODS = frozenset({"POST", "PUT", "PATCH", "DELETE"})
_MAX_TARGET = 200
_MAX_ACTOR = 254
_MAX_ACTION = 100


def _table(name: str) -> str:
    # Table names go into SQL text (they can't be parameters), so only fixed, plain names are allowed.
    if not _TABLE_NAME.match(name):
        raise ValueError(f"bad table name: {name!r}")
    return name


def _result(status: int) -> str:
    if status < 400:
        return "ok"
    if status in (401, 403):
        return "denied"
    return "failed"


def schema_sql(table: str = "admin_audit_log") -> str:
    """CREATE statements for the app's own schema function (db.py), which runs before AuditLog exists."""
    t = _table(table)
    return f"""
CREATE TABLE IF NOT EXISTS {t} (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor   TEXT NOT NULL DEFAULT '',
    action  TEXT NOT NULL,
    target  TEXT NOT NULL DEFAULT '',
    result  TEXT NOT NULL CHECK (result IN ('ok', 'denied', 'failed'))
);
CREATE INDEX IF NOT EXISTS {t}_at_idx ON {t} (at);
"""


class AuditLog:
    """Rows: (id BIGINT identity, at TIMESTAMPTZ, actor, action, target, result TEXT)."""

    def __init__(self, *, database: Database, table: str = "admin_audit_log",
                 retention_days: Callable[[], int] = lambda: 180):
        self._database = database
        self._table = _table(table)
        self._retention_days = retention_days

    def record(self, cur, *, actor: str | None, action: str, target: str = "", result: str = "ok") -> None:
        """Write one row and drop rows past the retention period."""
        if result not in ("ok", "denied", "failed"):
            raise ValueError(f"bad result: {result!r}")
        days = max(1, int(self._retention_days()))
        cur.execute(f"DELETE FROM {self._table} WHERE at < now() - make_interval(days => %s)", (days,))
        cur.execute(
            f"INSERT INTO {self._table} (actor, action, target, result) VALUES (%s, %s, %s, %s)",
            ((actor or "")[:_MAX_ACTOR], action[:_MAX_ACTION], (target or "")[:_MAX_TARGET], result),
        )

    def page(self, cur, *, before_id: int | None = None, limit: int = 50) -> list[dict]:
        """Newest first. Pass the last row's id as before_id for the next page."""
        limit = max(1, min(int(limit), 200))
        if before_id is None:
            cur.execute(f"SELECT id, at, actor, action, target, result FROM {self._table} "
                        "ORDER BY id DESC LIMIT %s", (limit,))
        else:
            cur.execute(f"SELECT id, at, actor, action, target, result FROM {self._table} "
                        "WHERE id < %s ORDER BY id DESC LIMIT %s", (int(before_id), limit))
        return [{"id": r[0], "at": r[1].isoformat(), "actor": r[2], "action": r[3], "target": r[4],
                 "result": r[5]} for r in cur.fetchall()]

    # ── the blueprint hook ──

    def attach(self, bp: Blueprint) -> None:
        bp.after_request(self._after_request)

    def _after_request(self, response):
        status = response.status_code
        if request.method not in _WRITE_METHODS and status != 403:
            return response
        actor = getattr(g, "admin_email", None) or getattr(g, "audit_actor", None)
        if status in (401, 403) and not actor:
            return response
        target = getattr(g, "audit_target", None)
        if target is None:
            target = ",".join(f"{k}={v}" for k, v in sorted((request.view_args or {}).items()))
        try:
            with self._database.connection() as conn:
                with conn.cursor() as cur:
                    self.record(cur, actor=actor, action=request.endpoint or request.path,
                                target=str(target), result=_result(status))
        except Exception as exc:  # noqa: BLE001 — the request's own work is done; don't fail it here
            log.error("audit log write failed: %s", type(exc).__name__)
        return response
