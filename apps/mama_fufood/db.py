def _seed(cur, dataset: str) -> None:
    """第一版公用資料(seed/ 資料夾)。

    只在「這個資料集一次都還沒發布過」時放入,之後一律由後台編輯與發布。
    """
    cur.execute("SELECT 1 FROM dataset_releases WHERE dataset = %s LIMIT 1", (dataset,))
    if cur.fetchone():
        return
    data = json.loads((SEED_DIR / f"{dataset}.json").read_text(encoding="utf-8"))
    content = data["content"]
    if dataset == "food_list":
        cur.execute("SELECT 1 FROM food_groups LIMIT 1")
        if cur.fetchone():
            return
        for g in content["groups"]:
            cur.execute(
                "INSERT INTO food_groups (id, name, emoji, sort, disabled, published) VALUES (%s,%s,%s,%s,%s,true)",
                (g["id"], g["name"], g["emoji"], g["sort"], g["disabled"]),
            )
        for f in content["foods"]:
            cur.execute(
                "INSERT INTO foods (id, group_id, name, emoji, sort, disabled, published)"
                " VALUES (%s,%s,%s,%s,%s,%s,true)",
                (f["id"], f["group_id"], f["name"], f["emoji"], f["sort"], f["disabled"]),
            )
        tables = ("food_groups", "foods")
    else:
        cur.execute("SELECT 1 FROM units LIMIT 1")
        if cur.fetchone():
            return
        for u in content["units"]:
            cur.execute(
                "INSERT INTO units (id, name, sort, is_default, disabled, published) VALUES (%s,%s,%s,%s,%s,true)",
                (u["id"], u["name"], u["sort"], u["default"], u["disabled"]),
            )
        tables = ("units",)
    # 明確指定 ID 放入之後,把 IDENTITY 的序號推到最大值,之後新增的才不會撞號。
    for table in tables:
        cur.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), (SELECT max(id) FROM {table}))")
    cur.execute(
        "INSERT INTO dataset_releases (dataset, version, format_version, content, published_by)"
        " VALUES (%s, %s, %s, %s, 'seed')",
        (dataset, data["version"], data["format_version"], Jsonb(content)),
    )


def _sync_formats(cur) -> None:
    """匯出格式的欄位定義跟著程式發布(SPEC 第 3 節第 6 項):部署時自動寫入,後台只能看。

    程式裡已經沒有的格式版本(例如上架前把第 1 版改稱第 0 版)從表裡刪掉:這張表只是程式的副本。"""
    cur.execute("DELETE FROM formats WHERE NOT (format_version = ANY(%s))", (list(export_formats.DEFINITIONS),))
    for version, definition in export_formats.DEFINITIONS.items():
        cur.execute(
            """
            INSERT INTO formats (format_version, definition, status, min_app_version)
            VALUES (%s, %s, %s, %s)
            ON CONFLICT (format_version) DO UPDATE
               SET definition = EXCLUDED.definition, status = EXCLUDED.status,
                   min_app_version = EXCLUDED.min_app_version, updated_at = now()
             WHERE formats.definition <> EXCLUDED.definition OR formats.status <> EXCLUDED.status
                OR formats.min_app_version <> EXCLUDED.min_app_version
            """,
            (version, Jsonb(definition), "current" if version == export_formats.CURRENT else "supported",
             definition["min_app_version"]),
        )


def _create_tables(cur) -> None:
    cur.execute(_DDL)
    cur.execute("INSERT INTO app_config (id) VALUES (true) ON CONFLICT DO NOTHING")
    _seed(cur, "food_list")
    _seed(cur, "units")
    _sync_formats(cur)


# ★ schema_lock 沿用搬過來之前的字串:切換期間舊服務與這裡連同一個資料庫,兩邊要排同一把鎖。
database = Database(
    "mama-fufood",
    url=lambda: config.get().database_url,
    schema=_create_tables,
    schema_lock="mama-fufood:schema",
    max_connections=5,
    timeout_seconds=lambda: config.get().db_timeout_seconds,
)


def connection():
    """`with db.connection() as conn:` — 測試會換掉這支,證明某條路徑完全不碰資料庫。"""
    return database.connection()
